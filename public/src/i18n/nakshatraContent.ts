export function getNakshatra(index: number, lang: Lang): NakLoc {
  const d = NAKSHATRA_DATA[index];
  if (lang === 'en') {
    return { name: d.name, deity: d.deity, symbol: d.symbol, gana: d.gana, yoni: d.yoni, nadi: d.nadi, strengths: d.strengths, challenges: d.challenges };
  }
  const sc = lang === 'hi' ? HI_SC[index] : NE_SC[index];
  return {
    name: DEVA.name[index], deity: DEVA.deity[index], symbol: DEVA.symbol[index],
    gana: DEVA.gana[d.gana], yoni: DEVA.yoni[d.yoni] ?? d.yoni, nadi: DEVA.nadi[d.nadi],
    strengths: sc[0], challenges: sc[1],
  };
}
